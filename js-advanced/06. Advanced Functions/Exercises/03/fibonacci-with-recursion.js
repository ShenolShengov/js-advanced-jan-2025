function getFibonator() {
    const memoization = {};
    let number = 0;

    function fibonacci(number) {
        if (number <= 1) {
            return number;
        }
        if (!memoization[number]) {
            memoization[number] = fibonacci(number - 1) + fibonacci(number - 2);
        }
        return memoization[number];
    }

    return () => fibonacci(number++);
}

